$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
& (Join-Path $PSScriptRoot 'Prepare-Environment.ps1')
$runId = Get-Date -Format 'yyyyMMdd-HHmmss'
$project = 'kt4-check-' + [Guid]::NewGuid().ToString('N').Substring(0, 8)
$results = Join-Path $root "artifacts/$runId"
New-Item -ItemType Directory -Force $results | Out-Null
$previousResults = $env:TEST_RESULTS_DIR
$env:TEST_RESULTS_DIR = $results.Replace('\', '/')
$compose = @('compose', '-f', 'compose.yaml', '-f', 'compose.tests.yaml', '-p', $project)
$testExit = 1

function Invoke-Compose {
    & docker @compose @args
    if ($LASTEXITCODE -ne 0) { throw "Docker Compose failed: $args" }
}

function Wait-Endpoint([string]$url) {
    # curl runs in the same private network as the applications.
    Invoke-Compose run --rm --no-deps tests curl --fail --silent --show-error --output /dev/null `
        --retry 60 --retry-delay 2 --retry-all-errors --retry-max-time 150 --max-time 10 $url
}

Push-Location $root
try {
    Invoke-Compose build web api tests
    Invoke-Compose up -d database api
    Wait-Endpoint 'http://api:8080/api/catalog-items'
    Invoke-Compose up -d web
    Wait-Endpoint 'http://web:18301/health'

    & docker @compose run --rm --no-deps tests 2>&1 | Tee-Object (Join-Path $results 'test-output.log')
    $testExit = $LASTEXITCODE
    & (Join-Path $PSScriptRoot 'Write-TestSummary.ps1') -ResultsDirectory $results
    & (Join-Path $PSScriptRoot 'Test-ApiOutage.ps1') -Project $project -ResultsDirectory $results
    $hashes = Get-ChildItem (Join-Path $root 'tests') -Recurse -File |
        Where-Object { $_.FullName -notmatch '[\\/](bin|obj)[\\/]' } |
        ForEach-Object { [ordered]@{ path = [IO.Path]::GetRelativePath($root, $_.FullName); sha256 = (Get-FileHash $_.FullName).Hash } }
    [ordered]@{
        timestampUtc = [DateTime]::UtcNow.ToString('o')
        upstreamCommit = (Get-Content 'upstream.lock.json' -Raw | ConvertFrom-Json).commit
        harnessBaseCommit = (& git rev-parse HEAD)
        branch = (& git branch --show-current)
        project = $project
        freshDatabase = $true
        exitCode = $testExit
        testSources = @($hashes)
    } | ConvertTo-Json | Set-Content (Join-Path $results 'run.json') -Encoding utf8
} finally {
    # The name is generated by this script; only its temporary project is removed.
    & docker @compose logs --no-color web api 2>&1 | Set-Content (Join-Path $results 'services.log') -Encoding utf8
    & docker @compose down --volumes --remove-orphans
    $env:TEST_RESULTS_DIR = $previousResults
    Pop-Location
}
Write-Host "Results: $results"
exit $testExit
